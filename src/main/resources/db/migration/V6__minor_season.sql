-- 선수의 시즌 마이너리그(트리플A ~ 루키) 출전 경기 수(이슈 #19). MLB Stats API에서 선수 정보와 같이 하루 한 번 받는다.
-- hitting_games: 타자로 나온 경기, pitching_games: 등판한 경기(정규시즌). fetched_at: 마지막으로 받은 시각(UTC)
-- 홈 시즌 기록에서 메이저 경기 수와 견줘 "올해 주로 마이너"인 선수를 가린다.
create table minor_season (
    id             bigint generated by default as identity primary key,
    player_id      bigint                   not null references player (id),
    season         int                      not null,
    hitting_games  int                      not null,
    pitching_games int                      not null,
    fetched_at     timestamp with time zone not null,
    constraint uk_minor_season_player_season unique (player_id, season)
);
