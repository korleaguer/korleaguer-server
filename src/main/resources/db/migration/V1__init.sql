-- 시각은 모두 UTC로 저장한다. 한국 시간 변환은 API 응답에서만 한다.

create table team (
    bdl_team_id  bigint primary key,
    abbreviation varchar(10),
    name_en      varchar(100),
    location     varchar(100),
    league       varchar(20)
);

create table player (
    id            bigint generated by default as identity primary key,
    name_ko       varchar(50) not null unique,
    name_en       varchar(100),
    position      varchar(50),
    bdl_player_id bigint unique,
    birth_place   varchar(100),
    active        boolean not null default true
);

-- 소속 이력. MVP는 API의 현재 팀으로 한 줄만 채운다.
create table affiliation (
    id         bigint generated by default as identity primary key,
    player_id  bigint  not null references player (id),
    team_id    bigint  not null references team (bdl_team_id),
    start_date date    not null,
    end_date   date,
    loan       boolean not null default false,
    -- 현재 소속(end_date null)은 선수마다 한 줄만 둔다.
    constraint uk_affiliation_current unique nulls not distinct (player_id, end_date)
);

create table game (
    bdl_game_id    bigint primary key,
    season         int                      not null,
    season_type    varchar(20),
    start_time_utc timestamp with time zone not null,
    home_team_id   bigint                   not null references team (bdl_team_id),
    away_team_id   bigint                   not null references team (bdl_team_id),
    home_score     int,
    away_score     int,
    status_state   varchar(20)              not null,
    venue          varchar(100)
);

create index idx_game_start_time on game (start_time_utc);

-- 선수별 경기 기록. 기록이 없는 칸은 null 이다.
create table appearance (
    id                 bigint generated by default as identity primary key,
    player_id          bigint not null references player (id),
    game_id            bigint not null references game (bdl_game_id),
    team_id            bigint not null references team (bdl_team_id),
    -- 타격
    at_bats            int,
    runs               int,
    hits               int,
    doubles            int,
    triples            int,
    home_runs          int,
    rbi                int,
    walks              int,
    strikeouts         int,
    hit_by_pitch       int,
    stolen_bases       int,
    sac_flies          int,
    plate_appearances  int,
    total_bases        int,
    -- 투구
    pitching_outs      int,
    hits_allowed       int,
    runs_allowed       int,
    earned_runs        int,
    walks_allowed      int,
    pitcher_strikeouts int,
    home_runs_allowed  int,
    pitch_count        int,
    wins               int,
    losses             int,
    saves              int,
    constraint uk_appearance_player_game unique (player_id, game_id)
);

create table ingest_log (
    id            bigint generated by default as identity primary key,
    kind          varchar(30)              not null,
    started_at    timestamp with time zone not null,
    finished_at   timestamp with time zone,
    status        varchar(30)              not null,
    message       varchar(1000),
    requests_used int
);
