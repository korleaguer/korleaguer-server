-- 데이터 출처를 balldontlie에서 MLB 공식 Stats API로 바꾼다(이슈 #11).
-- 아직 배포 전이라 이전 데이터(샘플)는 버리고, 표를 MLB 번호(gamePk, 팀 번호, 선수 번호) 기준으로 다시 만든다.
-- 앱이 뜨면 수집기가 다시 받는다. 시각은 계속 UTC로 저장한다.

drop table appearance;
drop table player_move;
drop table affiliation;
drop table game;
drop table team;
drop table player;
delete from ingest_log;

-- MLB 구단. 번호는 MLB 팀 번호(예: 137 = San Francisco Giants), 약어는 MLB 30개 구단 표에서 채운다.
create table team (
    mlb_team_id  bigint primary key,
    abbreviation varchar(10),
    name_en      varchar(100)
);

-- 선수. mlb_id는 명단(roster/baseball.yml)의 MLB 선수 번호다. 프로필 칸은 MLB 값이며 없으면 null 이다.
-- 키·몸무게·투타는 받은 값 그대로(예: 6' 0", 196, Left/Right) 저장하고 응답에서 바꾼다.
create table player (
    id               bigint generated by default as identity primary key,
    name_ko          varchar(50) not null unique,
    mlb_id           bigint unique,
    name_en          varchar(100),
    position         varchar(50),
    birth_place      varchar(100),
    active           boolean     not null default true,
    birth_date       date,
    height           varchar(20),
    weight           varchar(20),
    bats_throws      varchar(20),
    jersey           varchar(10),
    debut_year       int,
    age              int,
    level            varchar(10),
    level_team_name  varchar(100),
    level_checked_at timestamp with time zone
);

-- 지금 소속(MLB 구단). 마이너 팀에 있으면 그 팀의 MLB 구단이다.
create table affiliation (
    id         bigint generated by default as identity primary key,
    player_id  bigint  not null references player (id),
    team_id    bigint  not null references team (mlb_team_id),
    start_date date    not null,
    end_date   date,
    loan       boolean not null default false,
    constraint uk_affiliation_current unique nulls not distinct (player_id, end_date)
);

-- 메이저 경기(정규시즌·포스트시즌). 번호는 MLB gamePk다.
-- status_state: scheduled / in_progress / final / postponed / canceled / delayed / suspended (그 밖은 MLB 값 소문자)
-- final_at: 끝난 것을 처음 본 시각, checked_at: 박스스코어를 마지막으로 받은 시각
-- settled: 끝나고 3일이 지나 기록이 굳은 경기. 다시 받지 않는다.
create table game (
    game_pk        bigint primary key,
    season         int                      not null,
    season_type    varchar(20),
    start_time_utc timestamp with time zone not null,
    home_team_id   bigint                   not null references team (mlb_team_id),
    away_team_id   bigint                   not null references team (mlb_team_id),
    home_score     int,
    away_score     int,
    status_state   varchar(30)              not null,
    venue          varchar(100),
    final_at       timestamp with time zone,
    checked_at     timestamp with time zone,
    settled        boolean                  not null default false
);

create index idx_game_start_time on game (start_time_utc);

-- 선수별 경기 기록. 기록이 없는 칸은 null 이다.
create table appearance (
    id                 bigint generated by default as identity primary key,
    player_id          bigint not null references player (id),
    game_id            bigint not null references game (game_pk),
    team_id            bigint not null references team (mlb_team_id),
    -- 타격
    at_bats            int,
    runs               int,
    hits               int,
    doubles            int,
    triples            int,
    home_runs          int,
    rbi                int,
    walks              int,
    strikeouts         int,
    hit_by_pitch       int,
    stolen_bases       int,
    sac_flies          int,
    plate_appearances  int,
    total_bases        int,
    -- 투구
    pitching_outs      int,
    hits_allowed       int,
    runs_allowed       int,
    earned_runs        int,
    walks_allowed      int,
    pitcher_strikeouts int,
    home_runs_allowed  int,
    pitch_count        int,
    wins               int,
    losses             int,
    saves              int,
    constraint uk_appearance_player_game unique (player_id, game_id)
);

-- MLB 이동 기록(V3와 같다).
create table player_move (
    mlb_transaction_id bigint primary key,
    player_id          bigint      not null references player (id),
    move_date          date        not null,
    type_code          varchar(10),
    type_desc          varchar(100),
    description        varchar(1000),
    from_team_id       bigint,
    from_team_name     varchar(100),
    from_level         varchar(10),
    to_team_id         bigint,
    to_team_name       varchar(100),
    to_level           varchar(10)
);

create index idx_player_move_player on player_move (player_id, move_date);

-- 선수·시즌별로 시즌 기록(gameLog)을 한 번 다 받았다는 표시. 있으면 다시 백필하지 않는다.
create table player_season (
    id         bigint generated by default as identity primary key,
    player_id  bigint                   not null references player (id),
    season     int                      not null,
    fetched_at timestamp with time zone not null,
    constraint uk_player_season unique (player_id, season)
);
